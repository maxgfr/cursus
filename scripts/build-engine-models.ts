// Build-time only: the ids of the models the installed WebLLM runs, as the engine's worker lists them
// (src/workers/localModel.worker.ts), so the page can rank models without starting the engine.
// Run again after upgrading @mlc-ai/web-llm: src/core/ai/localModels.test.ts fails until then.
import { writeFile } from 'node:fs/promises'
import { ModelType, prebuiltAppConfig } from '@mlc-ai/web-llm'

const OUT = new URL('../src/core/ai/engineModels.ts', import.meta.url)
const ids = prebuiltAppConfig.model_list
  .filter((m) => (m.model_type ?? ModelType.LLM) === ModelType.LLM)
  .map((m) => m.model_id)
const source = `// Generated by scripts/build-engine-models.ts from @mlc-ai/web-llm's prebuiltAppConfig: do not edit.
/** Ids of the models the installed WebLLM runs (language models only, as the engine's worker lists them). */
export const ENGINE_MODELS: readonly string[] = [
${ids.map((id) => `  '${id}',`).join('\n')}
]
`
await writeFile(OUT, source)
console.log(`${ids.length} engine model ids written to ${OUT.pathname}`)
